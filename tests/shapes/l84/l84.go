// Package l84 holds the pure parts of lab entry L84 (spec §15): the compose override each cell
// writes, the verdict rules, and the results note, built from the cells and nothing else. The lab
// harness (tests/lab/l84_test.go, tag lab) and the systemd cell (tests/systemd/l84_test.go, tag
// systemd) both use it, so a note is never typed by hand.
package l84

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// Verdicts a cell can end with.
const (
	Pass   = "PASS"
	Fail   = "FAIL"
	NotRun = "NOT RUN"
	// Invalid is a cell that could not measure what it asks, a fault of the platform and not of the
	// product: the container's systemd rendering no credentials at all.
	Invalid = "INVALID"
)

// Row is one observation of a cell: a case and what was seen.
type Row struct{ Case, Observation string }

// Cell is one cell of L84. IDs: "a" (systemd LoadCredential=), "b-long" and "b-short" (Compose
// secrets:, both syntaxes), and "c-systemd", "c-long", "c-short" (a version added with no restart).
// "a" and "c-systemd" run in a Debian container; "a-host" and "c-host" are the same two questions on
// the runner's own systemd, and are the cells that decide whether a README may name LoadCredential=.
type Cell struct {
	ID, Title, Verdict string
	Rows               []Row
}

// Env is what the note records about the machine and the images.
type Env struct {
	Date, Docker, Compose, Kernel, Systemd, Images string
}

// Save writes cells as JSON to path (mode 0600): the systemd cell's hand-off to the lab test.
func Save(path string, cells []Cell) error {
	b, err := json.MarshalIndent(cells, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o600)
}

// Load reads what Save wrote.
func Load(path string) ([]Cell, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var cells []Cell
	if err := json.Unmarshal(b, &cells); err != nil {
		return nil, err
	}
	return cells, nil
}

func find(cells []Cell, id string) *Cell {
	for i := range cells {
		if cells[i].ID == id {
			return &cells[i]
		}
	}
	return nil
}

// Verdict is the verdict of cell id, NotRun when there is none.
func Verdict(cells []Cell, id string) string {
	if c := find(cells, id); c != nil && c.Verdict != "" {
		return c.Verdict
	}
	return NotRun
}

// MayOffer reports whether a README may name mech for a device key (spec §15 L84): its start cell
// and its no-restart cell both PASS. mech is "systemd", "long" or "short"; systemd's are the host cells.
func MayOffer(cells []Cell, mech string) bool {
	return Verdict(cells, startID(mech)) == Pass && Verdict(cells, addID(mech)) == Pass
}

// Merge returns base with every cell of extra replacing the cell of its ID (or added).
func Merge(base, extra []Cell) []Cell {
	out := append([]Cell(nil), base...)
	for _, e := range extra {
		if c := find(out, e.ID); c != nil {
			*c = e
		} else {
			out = append(out, e)
		}
	}
	return out
}

// Order is the cells' order in the note.
var Order = []string{"a", "a-host", "b-long", "b-short", "c-systemd", "c-host", "c-long", "c-short"}

func cellTitle(id string) string {
	return map[string]string{
		"a":         "(a) systemd LoadCredential= against fence.ReadSecret, in the Debian container",
		"a-host":    "(a) systemd LoadCredential= against fence.ReadSecret, on the runner's systemd with the shipped unit's hardening",
		"b-long":    "(b) Compose secrets:, long syntax (uid \"0\", gid \"65532\", mode 0440)",
		"b-short":   "(b) Compose secrets:, short syntax",
		"c-systemd": "(c) systemd, in the Debian container: a second LoadCredential= line, no restart",
		"c-host":    "(c) systemd on the runner: a second LoadCredential= line, no restart",
		"c-long":    "(c) Compose, long syntax: a second secrets: entry, no restart",
		"c-short":   "(c) Compose, short syntax: a second secrets: entry, no restart",
	}[id]
}

// Note is the results note for tests/lab/results/L84-systemd-docker.md.
func Note(env Env, cells []Cell) string {
	var b strings.Builder
	b.WriteString("# L84: host credential mechanisms against `fence.ReadSecret`\n\n")
	b.WriteString("Generated by `make lab-l84` (tests/lab/l84_test.go) from the cells below; edit the harness, not this file.\n\n")
	fmt.Fprintf(&b, "- Date: %s\n- Docker: %s\n- Compose: %s\n- Kernel: %s\n- systemd: %s\n- Images: %s\n- Capture pointer: none beyond this note; the cells' rows below are the observations (no packet capture applies: the cells measure file owners and modes under the fence)\n\n",
		nz(env.Date), nz(env.Docker), nz(env.Compose), nz(env.Kernel), nz(env.Systemd), nz(env.Images))
	b.WriteString("## Verdicts\n\n| Cell | Verdict |\n|---|---|\n")
	cells = full(cells)
	ids := ordered(cells)
	for _, id := range ids {
		fmt.Fprintf(&b, "| %s | %s |\n", cellTitle(id), Verdict(cells, id))
	}
	b.WriteString("\n")
	for _, id := range ids {
		c := find(cells, id)
		fmt.Fprintf(&b, "## %s: %s\n\n", cellTitle(id), Verdict(cells, id))
		if len(c.Rows) == 0 {
			b.WriteString("No observation.\n\n")
			continue
		}
		b.WriteString("| Case | Observation |\n|---|---|\n")
		for _, r := range c.Rows {
			fmt.Fprintf(&b, "| %s | %s |\n", cell(r.Case), cell(r.Observation))
		}
		b.WriteString("\n")
	}
	b.WriteString("## What the READMEs may say\n\n")
	for _, m := range []struct{ mech, name string }{{"systemd", "systemd `LoadCredential=`"}, {"long", "Compose `secrets:`, long syntax"}, {"short", "Compose `secrets:`, short syntax"}} {
		switch {
		case MayOffer(cells, m.mech):
			fmt.Fprintf(&b, "- %s: may be named for a device key ((start) and (c) both PASS).\n", m.name)
		case Verdict(cells, startID(m.mech)) == NotRun || Verdict(cells, addID(m.mech)) == NotRun:
			fmt.Fprintf(&b, "- %s: unmeasured (start %s, no-restart %s): not named for a device key.\n",
				m.name, Verdict(cells, startID(m.mech)), Verdict(cells, addID(m.mech)))
		default:
			fmt.Fprintf(&b, "- %s: not for a device key (start %s, no-restart %s); the encryption key only, if at all.\n",
				m.name, Verdict(cells, startID(m.mech)), Verdict(cells, addID(m.mech)))
		}
	}
	b.WriteString("\nThe register row stays open while any cell is NOT RUN.\n")
	return b.String()
}

func startID(mech string) string {
	if mech == "systemd" {
		return "a-host"
	}
	return "b-" + mech
}

func addID(mech string) string {
	if mech == "systemd" {
		return "c-host"
	}
	return "c-" + mech
}

func nz(s string) string {
	if strings.TrimSpace(s) == "" {
		return "not recorded"
	}
	return s
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}

// full is cells with a NOT RUN cell added for each ID of Order that has none.
func full(cells []Cell) []Cell {
	out := append([]Cell(nil), cells...)
	for _, id := range Order {
		if find(out, id) == nil {
			out = append(out, Cell{ID: id, Verdict: NotRun, Rows: []Row{{"state", "not yet run"}}})
		}
	}
	return out
}

// ordered is every cell ID of Order, then any other in sorted order.
func ordered(cells []Cell) []string {
	seen := map[string]bool{}
	for _, id := range Order {
		seen[id] = true
	}
	var rest []string
	for _, c := range cells {
		if !seen[c.ID] {
			rest = append(rest, c.ID)
		}
	}
	sort.Strings(rest)
	return append(append([]string(nil), Order...), rest...)
}
