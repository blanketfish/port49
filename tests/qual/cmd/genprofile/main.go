// Command genprofile turns one TestQualify evidence directory into a device
// profile and its golden (plan 11b). The stimulus is generated; reactions and
// acceptance rules are pre-filled and reviewed by hand (decision 52 ruling 1).
//
//	go run ./tests/qual/cmd/genprofile -evidence tests/lab/evidence/QUAL-<slug>-<platform> [-check]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/rhwendt/port49/internal/devicemock"
)

// takes is the -take keys.
var takes, keeps map[string]bool

func main() {
	evidence := flag.String("evidence", "", "a TestQualify evidence directory")
	check := flag.Bool("check", false, "write nothing; exit 1 when the generated stimulus differs from the committed profile's")
	take := flag.String("take", "", "comma-separated keys (reaction:step/on, acceptance:id, device_fact:id, engine_gap:id, golden:scenario) where the regenerated value wins over the committed one")
	keep := flag.String("keep", "", "comma-separated keys where the committed entry wins over a differing regenerated one")
	flag.Parse()
	takes, keeps = map[string]bool{}, map[string]bool{}
	for _, k := range strings.Split(*keep, ",") {
		if k != "" {
			keeps[k] = true
		}
	}
	for _, k := range strings.Split(*take, ",") {
		if k != "" {
			takes[k] = true
		}
	}
	if *evidence == "" {
		fmt.Fprintln(os.Stderr, "genprofile: -evidence is required")
		os.Exit(2)
	}
	if err := run1(*evidence, *check); err != nil {
		fmt.Fprintln(os.Stderr, "genprofile:", err)
		os.Exit(1)
	}
}

func run1(evidence string, check bool) error {
	p, g, err := Generate(evidence, ".")
	if err != nil {
		return err
	}
	path := filepath.Join("tests", "qual", "profiles", p.Platform, devicemock.Slug(p.Firmware)+".yaml")
	if check {
		committed, err := devicemock.Load(path, ".")
		if err != nil {
			return err
		}
		if !StimulusEqual(p, committed) {
			return fmt.Errorf("the generated stimulus differs from %s", path)
		}
		return nil
	}
	if old, err := devicemock.Load(path, "."); err == nil {
		oldG, gerr := devicemock.LoadGolden(p.Golden)
		var og *devicemock.Golden
		if gerr == nil {
			og = &oldG
		}
		if err := mergeHand(p, &g, old, og, takes, keeps); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := writeProfile(path, p, evidence); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(p.Golden), 0o755); err != nil {
		return err
	}
	if err := devicemock.WriteGolden(p.Golden, g); err != nil {
		return err
	}
	fmt.Printf("wrote %s and %s\n\n%s", path, p.Golden, checklist(p, g))
	return nil
}

// writeProfile writes the header comment and then the profile as YAML with
// indent 2. The header names the evidence by its repository path, never the
// path the command was given.
func writeProfile(path string, p *devicemock.Profile, _ string) error {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Generated by genprofile from %s at %s; stimulus is generated, reactions and acceptance are reviewed by hand (decision 52 ruling 1).\n",
		p.Vetted.Evidence, p.Vetted.Commit)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(p); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

// checklist is what the vetter confirms before committing: names, enums and
// ids only, never a value from the evidence.
func checklist(p *devicemock.Profile, g devicemock.Golden) string {
	var b strings.Builder
	b.WriteString("Review before committing:\n")
	b.WriteString("1. Reactions. Each is pre-filled as measured from port49's verdicts; confirm what the device did next against the note's cell text.\n")
	for _, r := range p.Reactions {
		out := ""
		if r.Outcome != "" {
			out = " (" + r.Outcome + ")"
		}
		fmt.Fprintf(&b, "   - %s %s -> %s%s [%s, pre-filled]\n", r.Step, r.On, r.Then, out, r.Status)
	}
	b.WriteString("2. Acceptance rules: a rule is measured only when a note for this firmware measured it (ruling 4).\n")
	for _, a := range p.Acceptance {
		cite := ""
		for _, s := range a.Sources {
			cite += ", " + s.Note
		}
		fmt.Fprintf(&b, "   - %s: %s, %s%s\n", a.ID, a.Kind, a.Status, cite)
	}
	b.WriteString("3. Review-left defaults:\n")
	if t := p.Stimulus.TLS; t != nil {
		fmt.Fprintf(&b, "   - client_chain=%s server_identity=%s\n", t.ClientChain, t.ServerIdentity)
		if t.FlightDelay == 0 {
			b.WriteString("   - no flight delay was observed: none written, and no flight_delay scenario\n")
		}
	} else {
		b.WriteString("   - none (no TLS)\n")
	}
	b.WriteString("4. Engine gaps:\n")
	for _, e := range p.EngineGaps {
		fmt.Fprintf(&b, "   - %s (code %q)\n", e.ID, e.Code)
	}
	if len(p.EngineGaps) == 0 {
		b.WriteString("   - none\n")
	}
	for _, f := range p.DeviceFacts {
		fmt.Fprintf(&b, "   - device fact %s [%s]: confirm it against the note's cell text\n", f.ID, f.Status)
	}
	b.WriteString("5. Golden outcomes against the note:\n")
	names := make([]string, 0, len(g.Scenarios))
	for n := range g.Scenarios {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "   - golden %s: %s\n", n, g.Scenarios[n].Outcome)
	}
	return b.String()
}
