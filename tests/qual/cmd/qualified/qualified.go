const header = `# Qualified platforms

This page is generated by ` + "`make qualified-platforms`" + ` from the committed device profiles, their goldens and the lab results notes they cite. It lists what the lab measured, not what port49 claims: a platform that is not here was not tested, and a row says only what its golden shows port49 answering.

`

const noneYet = "No platform has been measured yet.\n"

const columns = "| vendor | OS | version tested | TACACS+ 49 | TLS 300 | command authorization | command authorization over TLS | accounting | mock | status |\n" +
	"|---|---|---|---|---|---|---|---|---|---|\n"

// commandNotSent is the engine gap genprofile records when the device sends no
// per-command authorization (L18). A profile without it and without command
// steps reads "no": not applicable is never inferred from absence.
const commandNotSent = "command_authorization_not_sent"

type platformName struct{ vendor, os string }

// inventory maps a profile to its vendor and OS: the platform, or for the
// generic platform the lab platform.
var inventory = map[string]platformName{
	"arista_eos":        {"Arista", "EOS"},
	"cisco_nxos":        {"Cisco", "NX-OS"},
	"cisco_iosxe":       {"Cisco", "IOS XE"},
	"juniper_junos":     {"Juniper", "Junos"},
	"nokia_srlinux":     {"Nokia", "SR Linux"},
	"generic/cisco_xrd": {"Cisco", "IOS XR (XRd)"},
	// XRd's qual run gives cisco_iosxr a platform block in tests/qual/qual-policy.yaml (the
	// generic adapter renders nothing and XR then refuses every command), so its profile's
	// platform is cisco_iosxr, not generic.
	"cisco_iosxr": {"Cisco", "IOS XR (XRd)"},
}

type row struct {
	vendor, os, version string
	cells               []string
	notes               []string // operator-facing engine gaps ("operator_" ids) and device facts
}

// operatorGapPrefix marks an engine gap whose text an operator must read: the page
// prints it under the table.
const operatorGapPrefix = "operator_"

// reasonRx finds the register a gap's text cites, "(L76 cell b)", or the QUAL run that
// stands in for one, "(QUAL; as L18)".
var reasonRx = regexp.MustCompile(`\(((?:L\d+|QUAL; )[^)]*)\)`)

// factReasonRx finds what a device fact's text cites first: a register row,
// "(L73 cell a)", or the conformance cell that measured it, "(QUAL tls_token_login)".
var factReasonRx = regexp.MustCompile(`\(((?:L\d+|QUAL )[^)]*)\)`)

// tlsNoCommands is the citation of the profile's per-request fact, or "" and
// false when it records none.
func tlsNoCommands(facts []devicemock.DeviceFact) (found bool, reason string) {
	for _, f := range facts {
		if f.ID == devicemock.FactTLSPerRequestNoCommands {
			if m := factReasonRx.FindStringSubmatch(f.What); m != nil {
				return true, m[1]
			}
			return true, ""
		}
	}
	return false, ""
}

// commandReason is the parenthesised citation in the command gap's text, or "" when the
// profile records no gap. A gap that cites nothing reads "—".
func commandReason(gaps []devicemock.EngineGap) (found bool, reason string) {
	for _, e := range gaps {
		if e.ID == commandNotSent {
			if m := reasonRx.FindStringSubmatch(e.What); m != nil {
				return true, m[1]
			}
			return true, ""
		}
	}
	return false, ""
}

// specPath is the spec, under the repository root, whose §15 register says which cited rows are open.
const specPath = "docs/design/2026-08-23-policy-engine-spec.md"

var registerID = regexp.MustCompile(`\bL[0-9]+[a-z]?\b`)

// citedID is a register ID with the " cell" that may follow it ("L76 cell b").
var citedID = regexp.MustCompile(`\bL[0-9]+[a-z]?\b(?: cell\b)?`)

// cite appends ", open" to every register ID in text that reg reads as open: the docs lint refuses
// an open row asserted, and a cell that cites one says so. A closed or unknown ID is left alone
// (checkCited refuses an unknown one before any page is built).
func cite(text string, reg map[string]docgen.LabRow) string {
	return citedID.ReplaceAllStringFunc(text, func(m string) string {
		id, cell := strings.CutSuffix(m, " cell")
		if !reg[id].Open {
			return m
		}
		if cell {
			return id + ", open; cell" // "L76, open; cell b": the lint reads "ID, open" beside the ID
		}
		return id + ", open"
	})
}

// checkCited is an error naming every register ID in text that reg lacks: a cell never cites a row
// the register does not hold.
func checkCited(where, text string, reg map[string]docgen.LabRow) error {
	for _, id := range registerID.FindAllString(text, -1) {
		if _, ok := reg[id]; !ok {
			return fmt.Errorf("%s cites %s, which the spec's lab register does not hold", where, id)
		}
	}
	return nil
}

// Build returns the Markdown page. A row exists only where a profile loads, which
// needs every note it cites, and its golden loads. The spec's lab register decides
// how a cell cites a row (cite); a repository without it builds no page.
func Build(repoRoot string) (string, error) {
	spec, err := os.ReadFile(filepath.Join(repoRoot, specPath))
	if err != nil {
		return "", err
	}
	reg, err := docgen.LabRegister(spec)
	if err != nil {
		return "", err
	}
	for _, s := range []string{l80Runs, l80Refused, l80DeniedByPort49} {
		if err := checkCited("the TLS column", s, reg); err != nil {
			return "", err
		}
	}
	files, err := filepath.Glob(filepath.Join(repoRoot, "tests/qual/profiles/*/*.yaml"))
	if err != nil {
		return "", err
	}
	var rows []row
	for _, f := range files {
		p, err := devicemock.Load(f, repoRoot)
		if err != nil {
			return "", err
		}
		key := p.Platform
		if key == "generic" {
			key += "/" + p.LabPlatform
		}
		name, ok := inventory[key]
		if !ok {
			return "", fmt.Errorf("%s: platform %q is not in the inventory map", f, key)
		}
		if p.Golden == "" {
			return "", fmt.Errorf("%s: no golden", f)
		}
		g, err := devicemock.LoadGolden(filepath.Join(repoRoot, p.Golden))
		if err != nil {
			return "", fmt.Errorf("%s: %w", f, err)
		}
		gap, reason := commandReason(p.EngineGaps)
		var notes []string
		for _, e := range p.EngineGaps {
			if strings.HasPrefix(e.ID, operatorGapPrefix) {
				notes = append(notes, e.What)
			}
		}
		for _, f := range p.DeviceFacts {
			notes = append(notes, f.What)
		}
		tlsGap, tlsReason := tlsNoCommands(p.DeviceFacts)
		for _, s := range append([]string{reason, tlsReason}, notes...) {
			if err := checkCited(f, s, reg); err != nil {
				return "", err
			}
		}
		for i, n := range notes {
			notes[i] = cite(n, reg)
		}
		c := cells(p.Transports, g, gap, reason, reg)
		tc := tlsCommand(p.Transports, g, gap, reason, tlsGap, tlsReason, reg)
		switch {
		case !slices.Contains(p.Transports, "tls"):
		case p.HasFact(devicemock.FactTLSPerRequestDeniedRuns):
			tc = cite(l80Runs, reg)
		case p.HasFact(devicemock.FactTLSPerRequestDeniedRefused):
			tc = cite(l80Refused, reg)
		case p.HasFact(devicemock.FactTLSPerRequestDeniedByPort49):
			tc = cite(l80DeniedByPort49, reg)
		}
		c = slices.Insert(c, 3, tc)
		c[len(c)-1] = rowStatus(c[len(c)-1], tc)
		rows = append(rows, row{name.vendor, name.os, p.Firmware, c, notes})
	}
	slices.SortFunc(rows, func(a, b row) int {
		return cmp.Or(strings.Compare(a.vendor, b.vendor), strings.Compare(a.os, b.os), compareVersions(a.version, b.version))
	})
	var b strings.Builder
	b.WriteString(header)
	if len(rows) == 0 {
		b.WriteString(noneYet)
		return b.String(), nil
	}
	b.WriteString(columns)
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", r.vendor, r.os, r.version, strings.Join(r.cells, " | "))
	}
	first := true
	for _, r := range rows {
		for _, n := range r.notes {
			if first {
				b.WriteString("\n## What an operator must do\n\n")
				first = false
			}
			fmt.Fprintf(&b, "- **%s %s**: %s\n", r.vendor, r.version, n)
		}
	}
	return b.String(), nil
}

// cells are the table's last columns but command authorization over TLS, which
// Build inserts: 49, 300, command authorization (over 49, from token_login),
// accounting, mock and status. Accounting is read from token_login, or from
// tls_token_login for a TLS-only platform.
func cells(transports []string, g devicemock.Golden, commandGap bool, reason string, reg map[string]docgen.LabRow) []string {
	cmd := "—"
	if slices.Contains(transports, "tcp") {
		cmd = command(g.Scenarios["token_login"].Steps, commandGap, reason, reg)
	}
	return []string{tcp(transports, g), tlsCell(transports, g), cmd, accounting(g), "yes", status(transports, g, commandGap)}
}

// What the TLS column says once L80's cell measured a denied command over
// per-request TLS (ruling 2026-10-21): the outcome, in words an operator acts
// on. Either makes the row partial: a bypass never reads as a pass.
const (
	l80Runs    = "no: over per-request TLS, a command port49 denies runs (L80)"
	l80Refused = "no command authorization over per-request TLS; denied commands refused locally (L80)"
	// port49 was asked about the denied command and denied it: not a local refusal (review M2).
	l80DeniedByPort49 = "no: per-request TLS sent no command authorization for the login; the denied command was denied by port49 (L80)"
)

// tlsCommand is command authorization over TLS, read from tls_token_login: the
// per-request login, the device default. A device whose per-request TLS sends
// no command authorization (its profile's device fact, never inferred) reads
// "single-connection only" when tls_single_connection's golden holds both
// command answers, else "no (per-request; <citation>)" (review batch 2 C1, I3).
func tlsCommand(transports []string, g devicemock.Golden, commandGap bool, reason string, noCommands bool, factReason string, reg map[string]docgen.LabRow) string {
	if !slices.Contains(transports, "tls") {
		return "—"
	}
	if noCommands {
		if commandsAnswered(g.Scenarios["tls_single_connection"].Steps) {
			return "single-connection only (per-request: " + cite(factReason, reg) + ")"
		}
		return "no (per-request; " + cite(factReason, reg) + ")"
	}
	return command(g.Scenarios["tls_token_login"].Steps, commandGap, reason, reg)
}

func yn(ok bool) string {
	if ok {
		return "yes"
	}
	return "no"
}

func tcp(transports []string, g devicemock.Golden) string {
	if !slices.Contains(transports, "tcp") {
		return "—"
	}
	return yn(g.Scenarios["token_login"].Outcome == "login_ok")
}

func tlsCell(transports []string, g devicemock.Golden) string {
	if !slices.Contains(transports, "tls") {
		return "—"
	}
	return yn(g.Scenarios["tls_token_login"].Outcome == "login_ok")
}

// loginSteps are the steps of the login scenario the cells read.
func loginSteps(g devicemock.Golden) []devicemock.GoldenStep {
	if s, ok := g.Scenarios["token_login"]; ok {
		return s.Steps
	}
	return g.Scenarios["tls_token_login"].Steps
}

func hasStep(steps []devicemock.GoldenStep, name string, events ...string) bool {
	return slices.ContainsFunc(steps, func(s devicemock.GoldenStep) bool {
		return s.Step == name && slices.Contains(events, s.Event)
	})
}

func hasStepNamed(steps []devicemock.GoldenStep, name string) bool {
	return slices.ContainsFunc(steps, func(s devicemock.GoldenStep) bool { return s.Step == name })
}

func commandsAnswered(steps []devicemock.GoldenStep) bool {
	return hasStep(steps, "command_permitted", "author_pass_add", "author_pass_repl") && hasStep(steps, "command_denied", "author_fail")
}

// command is "yes" when a login's steps answered a permitted and a denied
// command, "— (reason)" when the profile records that the device sends none and
// the steps hold none (reason is the register its gap cites: L18 for Junos, L76
// cell b for SR Linux; reg marks an open row's ID "L18, open"), else "no".
func command(steps []devicemock.GoldenStep, commandGap bool, reason string, reg map[string]docgen.LabRow) string {
	if commandsAnswered(steps) {
		return "yes"
	}
	if commandGap && !hasStepNamed(steps, "command_permitted") && !hasStepNamed(steps, "command_denied") {
		if reason == "" {
			return "—"
		}
		return "— (" + cite(reason, reg) + ")"
	}
	return "no"
}

func accounting(g devicemock.Golden) string {
	return yn(hasStep(loginSteps(g), "account_stop", "acct_success"))
}

// status is re-vet pending for a golden marked pending_lab, qualified when every
// cell that applies is yes, else partial. A "—" cell does not apply.
func status(transports []string, g devicemock.Golden, commandGap bool) string {
	if g.PendingLab {
		return "re-vet pending"
	}
	cmd := "—"
	if slices.Contains(transports, "tcp") {
		cmd = command(g.Scenarios["token_login"].Steps, commandGap, "", nil)
	}
	for _, c := range []string{tcp(transports, g), tlsCell(transports, g), cmd, accounting(g)} {
		if c == "no" {
			return "partial"
		}
	}
	return "qualified"
}

// rowStatus is status with command authorization over TLS counted: anything
// but yes or a "—" that does not apply makes the row partial.
func rowStatus(st, tlsCmd string) string {
	if st == "qualified" && tlsCmd != "yes" && !strings.HasPrefix(tlsCmd, "—") {
		return "partial"
	}
	return st
}

// compareVersions orders versions with their digit runs compared as numbers, so
// 9.3 sorts before 10.1. Other text compares bytewise.
func compareVersions(a, b string) int {
	for a != "" && b != "" {
		da, db := digitRun(a), digitRun(b)
		if da > 0 && db > 0 {
			na, _ := strconv.ParseUint(a[:da], 10, 64)
			nb, _ := strconv.ParseUint(b[:db], 10, 64)
			if c := cmp.Compare(na, nb); c != 0 {
				return c
			}
			a, b = a[da:], b[db:]
			continue
		}
		if a[0] != b[0] {
			return cmp.Compare(a[0], b[0])
		}
		a, b = a[1:], b[1:]
	}
	return cmp.Compare(len(a), len(b))
}

// digitRun is the length of s's leading run of ASCII digits.
func digitRun(s string) int {
	n := 0
	for n < len(s) && s[n] >= '0' && s[n] <= '9' {
		n++
	}
	return n
}
