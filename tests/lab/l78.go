// L78 asks whether Junos refuses a login whose permit session reply totals more
// than 255 bytes with every attribute at most 255. Junos delivers a grant as
// user-permissions, deny-commands and allow-commands (platforms/1.3.0/
// juniper_junos.yaml), and the projection keeps each under 255 and fails
// closed past it (decision 26: deny-all, reason projection_fail_closed, and
// `port49 policy test` exits 1), so the reply can only grow by the three
// attributes together. A step is a role the projection renders to about Target
// bytes, chosen by `port49 explain` against the lab inventory's Junos nodes.

// l78Step is one policy: Deny deny rules and Allow allow rules over the base
// role. Want is the three attributes' bytes together. A FailClosed step is one
// the projection cannot carry: its deny-commands passes 255 and the session
// gets the fail-closed reply (124 bytes), so Want is not asserted.
type l78Step struct {
	Target, Deny, Allow, Want int
	FailClosed                bool
}

// l78Steps are the brief's totals where the projection reaches them. 375 is
// the most this run's roles reached with every attribute at most 255 (a sixth allow root
// adds the network bit and drops every allow); 400 and 600 ask for more and
// get the fail-closed reply.
var l78Steps = []l78Step{
	{Target: 200, Deny: 0, Allow: 1, Want: 208},
	{Target: 240, Deny: 0, Allow: 3, Want: 240},
	{Target: 256, Deny: 1, Allow: 2, Want: 258},
	{Target: 300, Deny: 2, Allow: 2, Want: 299},
	{Target: 375, Deny: 3, Allow: 5, Want: 375},
	{Target: 400, Deny: 4, Allow: 5, FailClosed: true},
	{Target: 600, Deny: 8, Allow: 5, FailClosed: true},
}

// l78Roots are the commands whose permits the projection sends as
// allow-commands beside `show **`, in the order a step takes them.
var l78Roots = []string{"ping", "traceroute", "telnet", "ssh", "mtrace"}

// l78Denies are keyword vectors of show commands, each a deny the projection
// proves from the keyword tree (so none is refused at load).
var l78Denies = []string{
	"show jdaf service", "show l2circuit auto-sensing", "show l2circuit connections", "show l2cpd task",
	"show l2vpn connections", "show lacp interfaces", "show lacp statistics", "show lacp timeouts",
}

// l78Bytes is the length of user-permissions, deny-commands and allow-commands
// (name, `=` and value) for a role of deny denies and allow allow roots over
// `show **`. The role is admin's ceiling with the six baseline denies the
// projection adds for every command `show **` leaves unpermitted, which is
// why deny-commands starts at 141 bytes.
func l78Bytes(deny, allow int) (perm, denyBytes, allowBytes int) {
	const permBytes, denyBase = len("user-permissions=view view-configuration"), 141
	denyBytes = denyBase
	for _, d := range l78Denies[:deny] {
		// `| *show +a +b *(\|.*)?`
		denyBytes += len("|") + len(" *") + len(strings.Join(strings.Fields(d), " +")) + len(` *(\|.*)?`)
	}
	if allow == 0 {
		return permBytes, denyBytes, 0
	}
	alts := make([]string, allow)
	for i, r := range l78Roots[:allow] {
		alts[i] = r + "( .*)?"
	}
	value := strings.Join(alts, "|")
	if allow > 1 {
		value = "(" + value + ")"
	}
	return permBytes, denyBytes, len("allow-commands=^") + len(value) + len("$")
}

// l78Policy is the policy a step runs under: one subject, the qual operator,
// granted a role on the Junos nodes alone, so no other platform's projection
// can refuse the file.
func l78Policy(s l78Step) string {
	permits := []string{"show **"}
	for _, r := range l78Roots[:s.Allow] {
		permits = append(permits, r+" **")
	}
	return fmt.Sprintf(`# L78 step %d (plan 11b): generated by tests/lab/l78.go, never edited by hand.
platform_set: 1.3.0
scopes:
  - {name: qual_junos, match: {platform: juniper_junos}, on_missing: include}
roles:
  - {name: l78, privilege: admin, permit: [%s], deny: [%s]}
subjects:
  - {name: qual_operator, identity: ["user:alice@slice.port49.test"], username: qual01, token_ttl: 60s}
grants:
  - {subject: qual_operator, scope: qual_junos, roles: [l78], max_privilege: admin}
`, s.Target, quoteAll(permits), quoteAll(l78Denies[:s.Deny]))
}

func quoteAll(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

// l78Row is one step's observation.
type l78Row struct {
	Target     int
	Parts      []int  // the byte length of each attribute the record carried
	Total      int    // their sum, from the authorize_session record
	Refused    string // the process log's line when the policy was refused at load
	LoggedIn   bool
	Counts     bool // `show version` ran under a permit reply (l78Grading.Counts)
	Lockout    bool
	Login      string
	Shown      string // the first line of the device's answer to `show version`, a Junos caret line skipped
	BreakGlass string // break-glass after the step
}

// l78Reply is the attribute lengths of a permitting authorize_session record's
// reply, name and `=` included, and their sum: the number the note cites.
func l78Reply(rec map[string]any) (parts []int, total int, ok bool) {
	if ev, _ := rec["event"].(string); ev != "authorize_session" {
		return nil, 0, false
	}
	if v, _ := rec["verdict"].(string); v != "permit" {
		return nil, 0, false
	}
	reply, _ := rec["reply"].(map[string]any)
	attrs, _ := reply["attributes"].([]any)
	if len(attrs) == 0 {
		return nil, 0, false
	}
	for _, a := range attrs {
		s, _ := a.(string)
		parts = append(parts, len(s))
		total += len(s)
	}
	return parts, total, true
}

// l78Grading is one token login's grade.
type l78Grading struct {
	Lockout bool   // refused to log in after a permit reply
	Counts  bool   // `show version` ran under a permit reply: what "no lockout up to" may cite
	OK      bool   // false when the step contradicts its reply: a refused permit, or a command run under deny-all
	Shown   string // the device's first answer line (qualRan's: a Junos caret line is skipped)
	Says    string
}

// l78Grade reads one token login: loggedIn is whether a session opened,
// record whether a permitting authorize_session record shows the reply port49
// sent, failClosed whether the step's reply is the fail-closed one (deny-all),
// out the device's answer to `show version`. A refusal to log in is a lockout
// only after a permit reply; with none logged, the run did not observe what
// the device was sent. Whether the command ran is qualRan's reading, so a
// refusal under a permit reply (a Junos that drops attributes past 255 bytes
// and refuses with `error: ...`) is a failed step, never a login that counts
// (final review I4).
func l78Grade(loggedIn, record, failClosed bool, total int, out string) l78Grading {
	ran, first := qualRan(out)
	silent := !ran && first == "no output"
	if silent {
		first = ""
	}
	g := l78Grading{Shown: first, OK: true}
	switch {
	case loggedIn && record && silent:
		g.OK, g.Says = false, "logged in; no output, so whether `show version` ran is unmeasured"
	case loggedIn && record && failClosed && !ran:
		g.Says = fmt.Sprintf("logged in; `show version` refused (deny-all) after a %d-byte reply", total)
	case loggedIn && record && failClosed:
		g.OK, g.Says = false, fmt.Sprintf("logged in and ran `show version` under the fail-closed reply of %d bytes", total)
	case loggedIn && record && ran:
		g.Counts, g.Says = true, fmt.Sprintf("logged in and ran `show version` after a %d-byte reply", total)
	case loggedIn && record:
		g.OK, g.Says = false, fmt.Sprintf("logged in; refused `show version` under a permit reply of %d bytes", total)
	case loggedIn:
		g.Says = "logged in; no authorize_session record showed the reply"
	case record:
		g.Lockout, g.Says = true, fmt.Sprintf("refused after a permit reply of %d bytes", total)
	default:
		g.Says = "not observed (no authorize_session record)"
	}
	return g
}

// l78Conclusion is the note's one-line result, in Q2's words when nothing
// locked a user out. Only a step whose permit reply let `show version` run
// counts toward the "no lockout up to" maximum.
func l78Conclusion(rows []l78Row, version string) string {
	most := 0
	for _, r := range rows {
		if r.Lockout {
			return fmt.Sprintf("lockout at %d bytes on %s", r.Total, version)
		}
		if r.Counts && r.Total > most {
			most = r.Total
		}
	}
	return fmt.Sprintf("no lockout up to %d bytes on %s; open for hardware Junos", most, version)
}
