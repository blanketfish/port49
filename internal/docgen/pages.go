// Header follows the front matter of every generated page. A page that carries it is written by
// `make docs`, and the drift test fails when the committed page differs from the generated one.
const Header = "<!-- generated by make docs from code; do not edit -->"

// Schema is one file an operator writes: the type its loader strict-decodes, the page that documents
// it, and the descriptions file that says what each key does.
type Schema struct {
	// File is the file's name, as a docs example titles a block: ```yaml title="port49d.yaml".
	File, Title, Page string
	Root              reflect.Type
	// Descriptions is the repository-relative path of the descriptions file.
	Descriptions string
	// Decode is the package's DecodeStrict: the loader's own decode, without the rest of the load.
	Decode func([]byte) error
}

// Schemas lists the six schema files. port49d.yaml and port49-broker.yaml share a root, a descriptions
// file and a page.
func Schemas() []Schema {
	const dir = "internal/docgen/descriptions/"
	return []Schema{
		{File: "port49d.yaml", Title: "port49d configuration", Page: "docs/site/reference/config/port49d.md",
			Root: reflect.TypeOf(config.FileSchema()), Descriptions: dir + "port49d.yaml", Decode: config.DecodeStrict},
		{File: "port49-broker.yaml", Title: "port49d configuration", Page: "docs/site/reference/config/port49d.md",
			Root: reflect.TypeOf(config.FileSchema()), Descriptions: dir + "port49d.yaml", Decode: config.DecodeStrictBroker},
		{File: "policy.yaml", Title: "Policy file reference", Page: "docs/site/reference/config/policy.md",
			Root: reflect.TypeOf(policy.FileSchema()), Descriptions: dir + "policy.yaml", Decode: policy.DecodeStrict},
		{File: "inventory.yaml", Title: "Inventory file reference", Page: "docs/site/reference/config/inventory.md",
			Root: reflect.TypeOf(admission.FileSchema()), Descriptions: dir + "inventory.yaml", Decode: admission.DecodeStrict},
		{File: "port49-inventory.yaml", Title: "port49-inventory configuration", Page: "docs/site/reference/config/port49-inventory.md",
			Root: reflect.TypeOf(inventory.FileSchema()), Descriptions: dir + "port49-inventory.yaml", Decode: inventory.DecodeStrict},
		{File: "config.yaml", Title: "Client configuration reference", Page: "docs/site/reference/config/client.md",
			Root: reflect.TypeOf(userconfig.FileSchema()), Descriptions: dir + "client.yaml", Decode: userconfig.DecodeStrict},
	}
}

// The two reserved entries of a descriptions file are not keys: the page's front-matter description and
// its introduction.
const (
	descDescription = "_description"
	descIntro       = "_intro"
	draftPrefix     = "DRAFT:"
)

// LoadDescriptions reads s's descriptions file under root.
func LoadDescriptions(root string, s Schema) (map[string]string, error) {
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(s.Descriptions)))
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	if err := yaml.Unmarshal(b, &out); err != nil {
		return nil, fmt.Errorf("%s: %w", s.Descriptions, err)
	}
	return out, nil
}

// ConfigPage is the reference page for s: every key of its root, in field order, with its type and the
// description desc holds. It fails, naming them all, if a key has no description, a description has no
// key, or an entry is still a DRAFT.
func ConfigPage(s Schema, desc map[string]string) (string, error) {
	keys := Keys(s.Root)
	var problems []string
	have := map[string]bool{descDescription: true, descIntro: true}
	for _, k := range keys {
		have[k.Path] = true
		d, ok := desc[k.Path]
		switch {
		case !ok || strings.TrimSpace(d) == "":
			problems = append(problems, "no description for "+k.Path)
		case strings.HasPrefix(strings.TrimSpace(d), draftPrefix):
			problems = append(problems, k.Path+" is still a DRAFT")
		}
	}
	for _, r := range []string{descDescription, descIntro} {
		d := strings.TrimSpace(desc[r])
		if d == "" {
			problems = append(problems, "no description for "+r)
		} else if strings.HasPrefix(d, draftPrefix) {
			problems = append(problems, r+" is still a DRAFT")
		}
	}
	var extra []string
	for p := range desc {
		if !have[p] {
			extra = append(extra, p)
		}
	}
	sort.Strings(extra)
	for _, p := range extra {
		problems = append(problems, "no key for description "+p)
	}
	if len(problems) > 0 {
		return "", fmt.Errorf("%s: %s", s.Descriptions, strings.Join(problems, "; "))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "---\ntitle: %s\ndescription: %s\n---\n\n%s\n\n# %s\n\n%s\n", jsonString(s.Title),
		jsonString(oneLine(desc[descDescription])), Header, s.Title, strings.TrimSpace(desc[descIntro]))

	var order []string
	groups := map[string][]Key{}
	for _, k := range keys {
		g := "Top-level keys"
		if i := strings.Index(k.Path, "."); i >= 0 {
			g = "`" + k.Path[:i] + "`"
		}
		if _, ok := groups[g]; !ok {
			order = append(order, g)
		}
		groups[g] = append(groups[g], k)
	}
	for _, g := range order {
		fmt.Fprintf(&b, "\n## %s\n\n| Key | Type | Description |\n|---|---|---|\n", g)
		for _, k := range groups[g] {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", k.Path, k.Type, cell(desc[k.Path]))
		}
	}
	return b.String(), nil
}

// BrokerSection is the part of port49d's page about port49-broker.yaml, which has port49d.yaml's schema
// under the broker's role. It is written from the loader's own table of refusals.
func BrokerSection() string {
	var b strings.Builder
	b.WriteString("\n## port49-broker.yaml\n\n" +
		"`port49-broker.yaml` has the schema above, read under the broker's role. The broker never speaks " +
		"TACACS+ and never holds a device key, so the loader refuses the keys below by name: a file that " +
		"names one does not load, and the error names the key. A few other keys are refused by the check of " +
		"their own block rather than by this table; the entries above mark them \"port49d.yaml only\".\n\n" +
		"| Refused key | Why |\n|---|---|\n")
	for _, r := range config.BrokerRefusals() {
		// The loader spells a block it refuses `keys:`; the table names the key.
		fmt.Fprintf(&b, "| `%s` | %s |\n", strings.TrimSuffix(r.Key, ":"), cell(r.Why))
	}
	return b.String()
}

// Pages is every generated file, from its repository-relative path to its contents.
func Pages(root string) (map[string]string, error) {
	out := map[string]string{}
	for _, s := range Schemas() {
		if _, done := out[s.Page]; done {
			continue
		}
		desc, err := LoadDescriptions(root, s)
		if err != nil {
			return nil, err
		}
		page, err := ConfigPage(s, desc)
		if err != nil {
			return nil, err
		}
		if s.File == "port49d.yaml" {
			page += BrokerSection()
		}
		out[s.Page] = page
	}
	spec, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(specPath)))
	if err != nil {
		return nil, err
	}
	if out[reasonPage], err = ReasonPage(spec); err != nil {
		return nil, err
	}
	desc, err := LoadDecisionLogDescriptions(root)
	if err != nil {
		return nil, err
	}
	if out[decisionLogPage], err = DecisionLogPage(spec, desc); err != nil {
		return nil, err
	}
	ms, err := Metrics()
	if err != nil {
		return nil, err
	}
	rules, err := os.ReadFile(filepath.Join(root, "deploy/alerts/port49.rules.yaml"))
	if err != nil {
		return nil, err
	}
	as, err := Alerts(rules)
	if err != nil {
		return nil, err
	}
	out[metricsPage] = MetricsPage(ms, as)
	readme, err := os.ReadFile(filepath.Join(root, "deploy/alerts/README.md"))
	if err != nil {
		return nil, err
	}
	if out[alertsPage], err = AlertsPage(as, readme); err != nil {
		return nil, err
	}

	reg, err := LabRegister(spec)
	if err != nil {
		return nil, err
	}
	for _, p := range DevicePages {
		ev, err := EvidenceFor(filepath.Join(root, "tests", "lab", "results"), p)
		if err != nil {
			return nil, err
		}
		out[evidenceDir+p.Slug+".md"] = EvidenceTable(ev, reg)
	}
	mk, err := os.ReadFile(filepath.Join(root, "mkdocs.yml"))
	if err != nil {
		return nil, err
	}
	if out[llmsPage], err = LLMsTxt(mk, filepath.Join(root, "docs", "site")); err != nil {
		return nil, err
	}
	return out, nil
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell is s as one table cell: one line, with the pipe escaped.
func cell(s string) string { return strings.ReplaceAll(oneLine(s), "|", `\|`) }
